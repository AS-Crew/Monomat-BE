-- V3: map.pending_public 컬럼 추가 (이슈 #76)
--
-- 배경:
--   공개(`is_public=true`) 상태는 비삭제 MapItem이 0개일 때 항상 false로
--   강제된다. 그러나 사용자가 맵 생성 시 "공개"를 요청했다가 아이템이 없어
--   비공개로 저장된 경우, 첫 아이템 추가 시점에 자동으로 공개로 전환해주려면
--   "사용자가 공개를 원했다"는 의도를 별도로 보존해야 한다.
--
--   pending_public = TRUE  → 의도는 공개, 검증 미달로 임시 비공개 상태
--   pending_public = FALSE → 의도 자체가 비공개
--
-- 기존 데이터:
--   기본값 FALSE로 채워진다. 기존 공개 맵은 이미 검증 통과 상태이므로
--   pending_public은 의미가 없고 FALSE면 충분하다.
-- =====================================================================

ALTER TABLE `map`
    ADD COLUMN `pending_public` BOOLEAN NOT NULL DEFAULT FALSE
        COMMENT '공개 의도 보존 플래그 (아이템 0개로 인한 임시 비공개 상태에서 자동 공개 전환 대상 표시)';
